    public DbSet<TransportMinutesLine> TransportMinutesLines => Set<TransportMinutesLine>();
    public DbSet<DealerPayment> Payments => Set<DealerPayment>();
    public DbSet<DealerPaymentLine> PaymentLines => Set<DealerPaymentLine>();

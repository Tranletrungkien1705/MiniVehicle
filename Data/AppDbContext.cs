        b.Entity<DealerPayment>().HasIndex(x => new { x.OrgId, x.PaymentNo }).IsUnique();
        b.Entity<StorageMaintenance>().HasIndex(x => new { x.OrgId, x.MtnNo }).IsUnique();
        b.Entity<PackingList>().HasIndex(x => new { x.OrgId, x.PackingListNo }).IsUnique();
        b.Entity<CustomsDeclaration>().HasIndex(x => new { x.OrgId, x.DeclarationNo }).IsUnique();
        b.Entity<CarBoxRequest>().HasIndex(x => new { x.OrgId, x.CBReqNo }).IsUnique();
        b.Entity<CarInvoice>().HasIndex(x => new { x.OrgId, x.InvoiceListCode }).IsUnique();
        b.Entity<GuaranteeExtension>().HasIndex(x => new { x.OrgId, x.GrtClaimExtNo }).IsUnique();
        b.Entity<ContractCancel>().HasIndex(x => new { x.OrgId, x.ContractCNo }).IsUnique();
        b.Entity<CarColorChange>().HasIndex(x => new { x.OrgId, x.ChangeNo }).IsUnique();
        b.Entity<BankBillMinutes>().HasIndex(x => new { x.OrgId, x.BankBillMnNo }).IsUnique();
        b.Entity<GuaranteeClaim>().HasIndex(x => new { x.OrgId, x.ClaimNo }).IsUnique();
        b.Entity<ContractOversea>().HasIndex(x => new { x.OrgId, x.ContractNo }).IsUnique();
        b.Entity<LetterOfCredit>().HasIndex(x => new { x.OrgId, x.LCNo }).IsUnique();
        b.Entity<RepairOrder>().HasIndex(x => new { x.OrgId, x.RoNo }).IsUnique();
        b.Entity<ServiceAppointment>().HasIndex(x => new { x.OrgId, x.AppNo }).IsUnique();
        b.Entity<TechnicalBulletin>().HasIndex(x => new { x.OrgId, x.BulletinNo }).IsUnique();
        b.Entity<BankDisbursement>().HasIndex(x => new { x.OrgId, x.RQ_BankingTransNo }).IsUnique();
    }
